const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

// 注音排在字的右邊、由上而下直排（課本的排法）：聲調標在符號右側，輕聲點放在最上面
function cell(c, z) {
  let neutral = '', tone = '', sym = z;
  if (sym.startsWith('˙')) { neutral = '˙'; sym = sym.slice(1); }
  if ('ˊˇˋ'.includes(sym.at(-1))) { tone = sym.at(-1); sym = sym.slice(0, -1); }
  return `<span class="zy"><span class="zc">${esc(c)}</span><span class="zb">${neutral ? `<i class="zn">${neutral}</i>` : ''}${sym}</span>${tone ? `<span class="zt">${tone}</span>` : ''}</span>`;
}

// 回傳加上注音的 HTML；查不到的字照原樣輸出
export function ruby(text) {
  let out = '';
  for (let i = 0; i < text.length; i++) {
    const two = text.slice(i, i + 2);
    if (WORDS[two]) {
      out += [...two].map((c, j) => cell(c, WORDS[two][j])).join('');
      i++;
      continue;
    }
    const c = text[i];
    out += Z[c] ? cell(c, Z[c]) : esc(c);
  }
  return out;
}

// 檢查用：列出沒有注音的中文字
export const missing = (text) => {
  const covered = new Set();
  for (let i = 0; i < text.length - 1; i++) if (WORDS[text.slice(i, i + 2)]) { covered.add(i); covered.add(i + 1); }
  return [...text].filter((c, i) => /[一-鿿]/.test(c) && !Z[c] && !covered.has(i));
};
